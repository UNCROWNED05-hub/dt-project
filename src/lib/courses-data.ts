export function getCourseBySlug(slug: string): Course | undefined {
  return COURSES.find((c) => c.slug === slug);
}

export function getChaptersForCourse(courseSlug: string): ChapterMeta[] {
  return CHAPTERS[courseSlug] || [];
}

export function getChapterBySlug(courseSlug: string, chapterSlug: string): ChapterMeta | undefined {
  const chapters = CHAPTERS[courseSlug] || [];
  return chapters.find((c) => c.slug === chapterSlug);
}

export function getAdjacentChapters(courseSlug: string, chapterSlug: string) {
  const chapters = CHAPTERS[courseSlug] || [];
  const index = chapters.findIndex((c) => c.slug === chapterSlug);
  return {
    prev: index > 0 ? chapters[index - 1] : null,
    next: index >= 0 && index < chapters.length - 1 ? chapters[index + 1] : null,
  };
}
